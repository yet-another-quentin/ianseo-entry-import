  function pickLang(lang) {
    return /^fr/i.test(String(lang || '')) ? 'fr' : 'en';
  }

  function make(lang) {
    const code = pickLang(lang);
    const dict = DICTS[code];
    function t(key, params) {
      let s = dict[key] != null ? dict[key] : (en[key] != null ? en[key] : key);
      // null → nothing; undefined or '' → "(empty)" (an empty value from the file is worth showing)
      if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] === null ? '' : params[k] == null || params[k] === '' ? dict.empty : String(params[k])));
      return s;
    }
    return { lang: code, t, locale: code === 'fr' ? 'fr-FR' : 'en-GB' };
  }

